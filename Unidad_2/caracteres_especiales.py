# Caracteres especiales en cadenas de texto

print("")
print("Hola \n Mundo") # Salto de linea
print("\t Mundo" )  # Tabulador
print("Hola \" \Mundo") # Comillas dobles
print('Hola \' Mundo') # Comillas simples 
print("Hola \\ Mundo") # Barra invertida
print("Hola \rMundo") # Retorno de carro
print("Hola \bMundo") # Retroceso
print("Hola \fMundo") # Avance de pagina