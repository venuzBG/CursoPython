# Operadores aritmeticos

a = 10
b = 3

suma = a + b
resta = a - b
multiplicacion = a * b
division = a / b #(retorna un float)
division_entera = a // b 
modulo = a % b
potencia = a ** b
print("Suma:", suma)
print("Resta:", resta)
print("Multiplicacion:", multiplicacion)
print("Division:", division)
