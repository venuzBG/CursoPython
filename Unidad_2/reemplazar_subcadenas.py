# Reemplazar subcadenas en una cadena

cadena = 'Hola, Mundo!'
nueva_cadena = cadena.replace('Mundo', 'a todos')

print(f'Cadena original: {cadena}')
print(f'Cadena modificada: {nueva_cadena}') #Devuelve la cadena original con la subcadena reemplazada por la nueva subcadena.

# Sustituir hola por adios

nueva_cadena = cadena.replace('Hola', 'Adiós')
print(f'Cadena modificada: {nueva_cadena}')