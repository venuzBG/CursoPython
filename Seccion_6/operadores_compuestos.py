# Operadores compuestos

a, b = 5, 3

print(f'Valores iniciales: a={a}, b={b}')

a+= b # a = a + b
print(f'Valor de a despues de a+=b: {a}')

a = 9
a-= b # a = a - b
print(f'Valor de a despues de a-=b: {a}')

a = 19
a*= b # a = a * b
print(f'Valor de a despues de a*=b: {a}')

a/= b # a = a / b
print(f'Valor de a despues de a/=b: {a:.2f}')

a//= b # a = a // b
print(f'Valor de a despues de a//=b: {a}')


