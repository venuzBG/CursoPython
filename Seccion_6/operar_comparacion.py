# Operadores d ecomparacion

a, b = 5, 3

print(f'Valores iniciales: a={a}, b={b}')

# Operador de igualdad
operacion = a == b
print(f'El resultado de a == b es: {operacion}')

# Operador de desigualdad
operacion = a != b
print(f'El resultado de a != b es: {operacion}')

# Operador mayor que
operacion = a > b
print(f'El resultado de a > b es: {operacion}')

# Operador menor que
operacion = a < b
print(f'El resultado de a < b es: {operacion}')

# Operador mayor o igual que
operacion = a >= b
print(f'El resultado de a >= b es: {operacion}')

# Operador menor o igual que
operacion = a <= b
print(f'El resultado de a <= b es: {operacion}')